// Migrate remaining existing entries by reading and upgrading
function migrateExisting() {
  const migrated = [];
  function walk(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith(".json") && entry.name !== "musical-behaviours.json" && entry.name !== "experience-chains.json") {
        const raw = JSON.parse(readFileSync(full, "utf8"));
        if (!raw.human_meaning && !raw.common_phrases) {
          const subdir = full.replace(ROOT + "\\", "").replace(ROOT + "/", "").split(/[/\\]/)[0];
          migrated.push({ subdir, entry: migrateV1(raw) });
        }
      }
    }
  }
  walk(ROOT);
  return migrated;
}

