import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../data/world-atlas");

function writeEntry(subdir, entry) {
  const dir = join(ROOT, subdir);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, `${entry.id.replace(/_/g, "-")}.json`);
  writeFileSync(file, JSON.stringify(entry, null, 2) + "\n", "utf8");
  return file;
}

function migrateV1(raw) {
  const name = raw.name ?? raw.label ?? raw.id.replace(/_/g, " ");
  return {
    id: raw.id,
    domain: raw.domain,
    name,
    description: raw.description ?? raw.physicalExperience ?? name,
    human_meaning: raw.human_meaning ?? raw.emotionalExperience ?? raw.physicalExperience ?? name,
    emotional_states: raw.emotional_states ?? (raw.emotionalExperience ? [raw.emotionalExperience] : []),
    hidden_emotions: raw.hidden_emotions ?? [],
    sensory_details: raw.sensory_details ?? raw.sensoryDetails ?? [],
    environment: raw.environment ?? [],
    activity: raw.activity ?? [],
    time_context: raw.time_context ?? [],
    weather_context: raw.weather_context ?? [],
    social_context: raw.social_context ?? [],
    energy_curve: raw.energy_curve ?? raw.expectedEnergy ?? "medium",
    emotional_arc: raw.emotional_arc ?? raw.narrativeArc ?? "",
    musical_behaviours: raw.musical_behaviours ?? raw.musicalBehaviours ?? [],
    related_experiences: raw.related_experiences ?? raw.relatedExperiences ?? [],
    common_phrases: raw.common_phrases ?? raw.recognitionCues ?? [],
    misleading_keywords: raw.misleading_keywords ?? [],
    ...(raw.playlistIntents ? { playlistIntents: raw.playlistIntents } : {}),
    ...(raw.inferredQualities ? { inferredQualities: raw.inferredQualities } : {}),
    ...(raw.typicalThoughts ? { typicalThoughts: raw.typicalThoughts } : {}),
    ...(raw.nearbyConcepts ? { nearbyConcepts: raw.nearbyConcepts } : {}),
  };
}

